    public const string TopicMarker = "📘";

    public static string FormatCommands(HelpCategory category) =>
        string.Join("\n", category.Commands.Select(c =>
            $"`/{c.Name}` {c.Summary}" + (Topics.Any(t => t.Commands.Contains(c.Name)) ? $" {TopicMarker}" : "")));

    public static string FormatTopicGuide() =>
        $"{TopicMarker} 표시가 있는 명령은 `/도움말 주제:`를 입력하고 주제를 고르면 규칙과 사용법을 자세히 볼 수 있어요.\n" +
        "주제: " + string.Join(" · ", Topics.Select(t => t.Name));

    public static HelpTopic? FindTopic(string? name) => Topics.FirstOrDefault(t => t.Name == name);

